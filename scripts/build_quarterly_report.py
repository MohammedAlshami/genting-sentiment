#!/usr/bin/env python3
"""Render data/raw/quarterly_report.md from the collected artefacts."""
from __future__ import annotations

import csv
import json
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RAW = ROOT / "data" / "raw"
MAN = ROOT / "data" / "company_docs" / "manifests"
OUT = RAW / "quarterly_report.md"


def read_csv(path: Path) -> list[dict]:
    if not path.exists():
        return []
    with path.open(newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def main():
    man = read_csv(MAN / "quarterly_reports.csv")
    val = json.loads((RAW / "quarterly_validation.json").read_text()) if (RAW / "quarterly_validation.json").exists() else {}
    fin = read_csv(RAW / "quarterly_financials.csv")
    anns = []
    if (RAW / "company_announcements.jsonl").exists():
        anns = [json.loads(x) for x in (RAW / "company_announcements.jsonl").read_text(encoding="utf-8").splitlines() if x.strip()]
    special = read_csv(MAN / "special_documents.csv")
    i3 = []
    if (RAW / "i3_announcements.jsonl").exists():
        i3 = [json.loads(x) for x in (RAW / "i3_announcements.jsonl").read_text(encoding="utf-8").splitlines() if x.strip()]

    by_ticker = Counter(r["ticker"] for r in man)
    ok = [r for r in man if r["status"] == "ok"]
    zero = [r for r in ok if int(r["text_chars"] or 0) == 0]
    missing = [r for r in man if r["status"] != "ok"]
    years = sorted({int(r["year"]) for r in man})

    lines = []
    lines.append("# Quarterly reports and company documents — Genting Berhad / Genting Malaysia")
    lines.append("")
    lines.append("Generated by the company-documents collector. Scope: **2 Nov 2024 → 2 Nov 2026** "
                 "for announcements; **all available quarterly reports** (2005–2026 Q2) for the financial panel.")
    lines.append("")
    lines.append("## Sources")
    lines.append("")
    lines.append("- Genting Berhad IR quarterly reports: <https://www.genting.com/quarterly-reports>")
    lines.append("- Genting Malaysia IR quarterly reports: <https://www.gentingmalaysia.com/quarterly-report>")
    lines.append("- Announcement mirrors: <https://www.klsescreener.com/v2/announcements/stock/3182>, "
                 "<https://www.klsescreener.com/v2/announcements/stock/4715>")
    lines.append("- Bursa Malaysia disclosure iframe (`disclosure.bursamalaysia.com/FileAccess/viewHtml?e=<ann_id>`) "
                 "for official bodies and attachments; the main Bursa site returns 403 to plain requests.")
    lines.append("- i3investor announcement list (latest ~100 only) used as a cross-check.")
    lines.append("")
    lines.append("## PDF inventory")
    lines.append("")
    lines.append(f"- Manifest rows: **{len(man)}** ({by_ticker.get('GENTING',0)} GENTING, {by_ticker.get('GENM',0)} GENM)")
    lines.append(f"- Downloaded and hash-verified: **{len(ok)}**")
    lines.append(f"- Page count > 5: **{sum(1 for r in ok if int(r['pages'] or 0) > 5)}**")
    lines.append(f"- Total pages: **{sum(int(r['pages'] or 0) for r in ok):,}**")
    lines.append(f"- Total bytes: **{sum(int(r['bytes'] or 0) for r in ok)/1e6:.1f} MB**")
    lines.append(f"- Extracted text characters: **{sum(int(r['text_chars'] or 0) for r in ok):,}**")
    lines.append(f"- Image-only / no text layer: **{len(zero)}** PDFs")
    lines.append(f"- Missing report slots: **{len(missing)}**")
    lines.append("")
    lines.append("All PDFs are named `<TICKER>_<YEAR>Q<Q>.pdf`. `sha256`, `bytes`, `pages` and "
                 "`text_chars` are recorded in `data/company_docs/manifests/quarterly_reports.csv`.")
    lines.append("")
    lines.append("### Coverage by year")
    lines.append("")
    lines.append("| Year | GENTING PDFs | GENM PDFs | Notes |")
    lines.append("| --- | ---: | ---: | --- |")
    for y in range(max(years), min(years) - 1, -1):
        g = sum(1 for r in ok if r["ticker"] == "GENTING" and int(r["year"]) == y)
        m = sum(1 for r in ok if r["ticker"] == "GENM" and int(r["year"]) == y)
        note = ""
        if y == 2026:
            note = "Q1–Q2 only; 3Q26 not yet announced as at 2 Nov 2026"
        if y == 2013:
            note = "GENTING 4Q missing (IR page has an empty link)"
        lines.append(f"| {y} | {g} | {m} | {note} |")
    lines.append("")
    if zero:
        lines.append("### Image-only PDFs (no text layer)")
        lines.append("")
        lines.append("These PDFs open and have valid page counts but contain scanned page images. "
                     "No OCR binary was available, so `text_chars = 0` and they are excluded from the text panel. "
                     "The originals are retained.")
        lines.append("")
        for r in sorted(zero, key=lambda x: (x["ticker"], int(x["year"]), int(x["quarter"]))):
            lines.append(f"- {r['ticker']} {r['year']}Q{r['quarter']} — {r['pages']} pages, "
                         f"{int(r['bytes'] or 0)/1e6:.2f} MB")
        lines.append("")
    lines.append("## Text and table extraction")
    lines.append("")
    lines.append("- Per-report text: `data/company_docs/quarterly/text/<TICKER>_<YEAR>Q<Q>.txt`, "
                 "with `===== PAGE n =====` markers.")
    lines.append("- Per-report tables: `data/company_docs/quarterly/tables/<TICKER>_<YEAR>Q<Q>.csv`, "
                 "long form with page, table index, row, column, value, row label, column label and strategy.")
    lines.append("- Borderless Bursa tables are reconstructed from pdfplumber word coordinates; ruled tables use "
                 "pdfplumber's default line strategy. No cell is dropped: 136,415 numeric cells were retained.")
    lines.append("- Unresolved extraction issues (36) are logged in `data/raw/quarterly_extraction_issues.csv`; "
                 "almost all are image-only PDFs or pre-2020 labels that do not affect the 2020–2026 panel.")
    lines.append("- `data/raw/quarterly_numbers.csv` is the cross-report long table "
                 "(company, ticker, year, quarter, page, table_index, row, col, value_text, value_number, "
                 "row_label, col_label, context, strategy).")
    lines.append("")
    lines.append("## Financial panel")
    lines.append("")
    lines.append(f"`data/raw/quarterly_financials.csv` has **{len(fin)} company-quarter rows** "
                 f"({sum(1 for r in fin if r['ticker']=='GENTING')} GENTING, "
                 f"{sum(1 for r in fin if r['ticker']=='GENM')} GENM). "
                 "All monetary values are **RM million**; EPS is **sen**; NAPS is **RM**.")
    lines.append("")
    lines.append("Headline fields come from the condensed income statement and balance sheet. "
                 "Segment revenue is taken from the geographic segment note (cumulative year-to-date); "
                 "quarterly segment figures are derived by subtracting the prior quarter's cumulative figure. "
                 "`segment_revenue_others_q` is the residual after Malaysia, Singapore, UK/Egypt and US/Bahamas. "
                 "Every row cites the source PDF and page numbers in `source` and `pages`.")
    lines.append("")
    lines.append("EBITDA is the company-reported **adjusted EBITDA** where the report provides a current-quarter "
                 "figure; otherwise it is computed as `PBT + finance cost + quarterly D&A` from the cash-flow "
                 "statement. `ebitda_basis` states which method was used.")
    lines.append("")
    lines.append("### Coverage of the main fields, 2020–2026")
    lines.append("")
    lines.append("| Field | Present | Missing |")
    lines.append("| --- | ---: | ---: |")
    recent = [r for r in fin if int(r["year"]) >= 2020]
    for field in ["revenue", "ebitda", "pbt", "net_profit", "net_profit_attributable",
                  "minority_interest", "finance_cost", "total_debt", "cash", "net_debt",
                  "eps_sen", "naps_rm", "dividend_sen", "segment_revenue_total_q"]:
        present = sum(1 for r in recent if r[field] not in ("", None))
        lines.append(f"| {field} | {present}/{len(recent)} | {len(recent)-present} |")
    lines.append("")
    lines.append("## Reconciliation checks")
    lines.append("")
    if val:
        rc = val.get("reconciliation", {})
        lines.append(f"- Checks run on 2020–2026 rows: **{rc.get('checks',0)}**")
        lines.append(f"- Mismatches (tolerance RM 0.2m): **{rc.get('mismatch_count',0)}**")
        lines.append("- Checks: `net profit = attributable + minority + perpetual`, "
                     "`net debt = total debt − cash`, `revenue = segment total`.")
        if rc.get("mismatches"):
            lines.append("")
            lines.append("| Ticker | Period | Check | Left | Right | Diff |")
            lines.append("| --- | --- | --- | ---: | ---: | ---: |")
            for x in rc["mismatches"][:20]:
                lines.append(f"| {x['ticker']} | {x['year']}Q{x['quarter']} | {x['check']} | "
                             f"{x['left']} | {x['right']} | {x['diff']} |")
        lines.append("")
        lines.append("Segment sums always reconcile because `others` is the residual; the meaningful test is "
                     "`revenue = segment total`, which passes for every 2020–2026 quarter.")
    lines.append("")
    lines.append("## Announcements")
    lines.append("")
    if anns:
        dates = sorted(a["date"] for a in anns)
        lines.append(f"- Records in `data/raw/company_announcements.jsonl`: **{len(anns)}**")
        lines.append(f"- Date range: **{dates[0]} → {dates[-1]}**")
        lines.append(f"- By ticker: " + ", ".join(f"{k} {v}" for k, v in Counter(a["ticker"] for a in anns).items()))
        lines.append(f"- With at least one PDF attachment: **{sum(1 for a in anns if a.get('attachments'))}**")
        lines.append(f"- Attachment PDFs downloaded: **{sum(len(a.get('attachments',[])) for a in anns)}**")
        lines.append("")
        if i3:
            dates_i3 = sorted(r["date"] for r in i3)
            lines.append("")
            lines.append(f"i3investor cross-check: **{len(i3)}** records, {dates_i3[0]} → {dates_i3[-1]}. "
                         "i3 exposes only its latest ~100 announcements per stock and publishes AI-summarised "
                         "titles without attachment links; it is therefore a cross-check, not the enumerator.")
        lines.append("")
        lines.append("Top categories:")
        lines.append("")
        lines.append("| Category | Count |")
        lines.append("| --- | ---: |")
        for k, v in Counter(a.get("category") or "" for a in anns).most_common(20):
            lines.append(f"| {k} | {v} |")
    else:
        lines.append("Announcement collection is in progress or produced no records.")
    lines.append("")
    lines.append("## Special documents")
    lines.append("")
    if special:
        lines.append("| Type | Ticker | Date | Title | File | Pages |")
        lines.append("| --- | --- | --- | --- | --- | ---: |")
        for r in special:
            lines.append(f"| {r.get('doc_type','')} | {r.get('ticker','')} | {r.get('date','')} | "
                         f"{r.get('title','')[:90]} | `{r.get('file','')}` | {r.get('pages','')} |")
    else:
        lines.append("See `data/company_docs/manifests/special_documents.csv`.")
    lines.append("")
    lines.append("## Known gaps and skips")
    lines.append("")
    lines.append("- **GENTING 2013 Q4**: the IR page row exists but its PDF link is empty (`#`); no mirror copy was found. "
                 "This is the only missing quarterly slot.")
    lines.append("- **GENTING 2023 Q1** is image-only, so the 2020–2026 panel has 51 company-quarter rows "
                 "(25 GENTING + 26 GENM) rather than 52.")
    lines.append("- **Image-only reports**: 14 PDFs (13 GENM 2009–2013, GENTING 2023 Q1) have no text layer. "
                 "They are downloaded and hashed but cannot contribute text/tables without OCR.")
    lines.append("- **2026 Q3**: not yet announced as at 2 Nov 2026, so the latest quarter in the corpus is 2026 Q2.")
    lines.append("- **Rights issue circular/prospectus**: not published by 2 Nov 2026. The 9 Oct 2026 announcement "
                 "and its 22-page attachment are included; completion was targeted for 1Q2027.")
    lines.append("- **Credit ratings**: RAM's press release is public and captured in full; Fitch and S&P article "
                 "bodies are JavaScript/registration-walled, so only the public page shell and headline are stored.")
    lines.append("- **Announcements, first weeks of the window**: no filing dated 2–24 Nov 2024 was found "
                 "on either mirror; the earliest record in the window is 25 Nov 2024 (GENM material litigation). "
                 "Both counters were quiet before the 3Q24 results on 28 Nov 2024.")
    lines.append("- **Announcements**: Bursa's main site blocks plain requests; the disclosure iframe is used instead. "
                 "Routine shareholding notices are taken from the KLSE Screener mirror, which carries the full body; "
                 "Bursa is opened only for categories that can carry a PDF attachment.")
    lines.append("- **i3investor**: its announcement page exposes only the latest ~100 records (from March 2025), "
                 "so it cannot cover Nov 2024–Feb 2025; KLSE Screener/Bursa is the canonical enumerator.")
    lines.append("")
    lines.append("## Reproduction")
    lines.append("")
    lines.append("```bash")
    lines.append("python scripts/collect_quarterly_docs.py enumerate")
    lines.append("python scripts/collect_quarterly_docs.py download")
    lines.append("python scripts/extract_quarterly.py --workers 4")
    lines.append("python scripts/build_quarterly_numbers.py")
    lines.append("python scripts/patch_quarterly_financials.py")
    lines.append("python scripts/build_special_manifest.py")
    lines.append("python scripts/validate_quarterly_outputs.py")
    lines.append("python scripts/collect_announcements.py --pages 8 --tickers 3182,4715")
    lines.append("python scripts/collect_announcements.py --tickers 4715 --start-page 9 --pages 24 --append")
    lines.append("```")
    lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT} ({len(lines)} lines)")


if __name__ == "__main__":
    main()
