#!/usr/bin/env python3
"""Build the website's history series from real prices + LLM sentiment."""

from __future__ import annotations

import csv
import json
import sqlite3
from datetime import datetime, timedelta, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "site" / "src" / "data" / "gentingHistory.ts"
PRICES = ROOT / "analysis" / "02_prices_monthly_10y.csv"
DB = ROOT / "data" / "genting.db"
MYT = timezone(timedelta(hours=8))


def main() -> None:
    prices = list(csv.DictReader(PRICES.open()))
    months = [r["month"] for r in prices]
    genm = {r["month"]: float(r["GENM"]) for r in prices}
    gent = {r["month"]: float(r["GENTING"]) for r in prices}

    conn = sqlite3.connect(DB)
    conn.row_factory = sqlite3.Row
    rows = conn.execute(
        """
        SELECT s.score, s.label, s.confidence,
               substr(datetime(r.created_utc,'unixepoch','+8 hours'),1,7) AS month,
               r.source
        FROM sentiment_llm s
        JOIN replies r ON r.id = s.reply_id
        """
    ).fetchall()

    by_month: dict[str, list[sqlite3.Row]] = {}
    for row in rows:
        by_month.setdefault(row["month"], []).append(row)

    real: dict[str, dict] = {}
    for month, items in by_month.items():
        n = len(items)
        scores = [i["score"] for i in items]
        labels = [i["label"] for i in items]
        real[month] = {
            "sentiment": sum(scores) / n,
            "n": n,
            "bull": labels.count("bullish") / n,
            "bear": labels.count("bearish") / n,
            "neutral": labels.count("neutral") / n,
        }

    # Interpolate months with no classified replies so the line is continuous.
    known = [m for m in months if m in real]
    series = []
    for month in months:
        if month in real:
            r = real[month]
            series.append({
                "month": month,
                "genm": round(genm[month], 3),
                "genting": round(gent[month], 3),
                "sentiment": round(r["sentiment"], 4),
                "n": r["n"],
                "bull": round(r["bull"], 3),
                "bear": round(r["bear"], 3),
                "modelled": False,
            })
            continue

        before = [m for m in known if m < month]
        after = [m for m in known if m > month]
        if before and after:
            a, b = before[-1], after[0]
            wa = int(month[:4]) * 12 + int(month[5:]) - (int(a[:4]) * 12 + int(a[5:]))
            wb = int(b[:4]) * 12 + int(b[5:]) - (int(month[:4]) * 12 + int(month[5:]))
            value = (real[a]["sentiment"] * wb + real[b]["sentiment"] * wa) / (wa + wb)
        elif before:
            value = real[before[-1]]["sentiment"]
        elif after:
            value = real[after[0]]["sentiment"]
        else:
            value = 0.5
        series.append({
            "month": month,
            "genm": round(genm[month], 3),
            "genting": round(gent[month], 3),
            "sentiment": round(value, 4),
            "n": 0,
            "bull": 0,
            "bear": 0,
            "modelled": True,
        })

    real_points = [p for p in series if not p["modelled"]]
    mx = sum(p["sentiment"] for p in real_points) / len(real_points)
    my = sum(p["genm"] for p in real_points) / len(real_points)
    num = sum((p["sentiment"] - mx) * (p["genm"] - my) for p in real_points)
    den = (
        sum((p["sentiment"] - mx) ** 2 for p in real_points)
        * sum((p["genm"] - my) ** 2 for p in real_points)
    ) ** 0.5
    corr = num / den if den else 0

    total_replies = conn.execute("SELECT count(*) FROM replies").fetchone()[0]
    classified = conn.execute("SELECT count(*) FROM sentiment_llm").fetchone()[0]
    articles = conn.execute("SELECT count(*) FROM articles").fetchone()[0]
    sources = [r[0] for r in conn.execute(
        "SELECT source FROM sentiment_llm s JOIN replies r ON r.id=s.reply_id "
        "GROUP BY r.source ORDER BY count(*) DESC"
    )]

    header = """// Generated by scripts/build_site_history.py — do not edit by hand.
// GENM / GENTING closes are real month-end Bursa prices.
// Sentiment is the DeepSeek v3 rubric monthly mean (0 = max bearish, 0.5 = neutral,
// 1 = max bullish). Months without enough classified replies are interpolated and
// flagged modelled: true; the appendix shows the sample size for every month.

export type HistoryPoint = {
  month: string;
  genm: number;
  genting: number;
  sentiment: number;
  n: number;
  bull: number;
  bear: number;
  modelled: boolean;
};

export const corpusStats = """
    stats = {
        "replies": total_replies,
        "classified": classified,
        "articles": articles,
        "months": len(months),
        "measuredMonths": len(real_points),
        "sources": sources,
        "sameMonthCorrelation": round(corr, 3),
    }
    OUT.write_text(
        header
        + json.dumps(stats, indent=2)
        + ";\n\nexport const historySeries: HistoryPoint[] = "
        + json.dumps(series, separators=(",", ":"))
        + ";\n"
    )
    print("wrote", OUT)
    print(json.dumps(stats, indent=2))
    print("mean", round(mx, 3), "range", min(p["sentiment"] for p in real_points), max(p["sentiment"] for p in real_points))


if __name__ == "__main__":
    main()
